#!/usr/bin/env python3
"""Generates Red Alert's global rules (`RulesClass`) from the original sources.

* Fields and their C++ types come from REDALERT/RULES.H.
* Defaults come from the RulesClass constructor's initialiser list (and the FIXIT_CSII
  assignments in its body) in REDALERT/RULES.CPP.
* Which INI section and key each field is read from, and with which getter, come from the
  straight-line `Field = ini.Get_X(SECTION, "Key", default);` statements in the reading
  functions listed in READERS. Loops and other special cases (powerups, land types,
  themes, objects) are hand-written in rules/mod.rs.

Also generates the weapon, warhead, projectile and crate name enums.

Usage (from the repository root): python3 rust/tools/gen_ra_rules.py
Rewrites rust/crates/cnc-ra/src/rules/global.rs and rules/names.rs (run `cargo fmt` after).
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
RA = ROOT / "REDALERT"
OUT = ROOT / "rust" / "crates" / "cnc-ra" / "src" / "rules"
READERS = ["General", "MPlayer", "Recharge", "Heap_Maximums", "AI", "IQ"]

header = (RA / "RULES.H").read_text(encoding="latin-1")
source = (RA / "RULES.CPP").read_text(encoding="latin-1")
const_cpp = (RA / "CONST.CPP").read_text(encoding="latin-1")
bbdata = (RA / "BBDATA.CPP").read_text(encoding="latin-1")


def snake(name: str) -> str:
    s = re.sub(r"(?<=[a-z0-9])(?=[A-Z])|(?<=[A-Z])(?=[A-Z][a-z])", "_", name).lower()
    s = re.sub(r"_+", "_", s)
    return {"type": "kind"}.get(s, s)


def camel(name: str) -> str:
    parts = re.split(r"[^A-Za-z0-9]+", name)
    out = "".join(p[:1].upper() + p[1:] for p in parts if p)
    return ("T" + out) if out[:1].isdigit() else out


# ---------------------------------------------------------------------------------------
# Name enums.

def named_enum(rust_name, doc, names, repr_ty="u8"):
    lines = [f"    /// {doc}", f"    pub enum {rust_name}: {repr_ty} {{"]
    used = set()
    for i, n in enumerate(names):
        v = camel(n)
        while v in used:
            v += "X"
        used.add(v)
        lines.append(f"        /// `{n}`.")
        lines.append(f'        {v} = {i} => "{n}",')
    lines.append("    }")
    return "cnc_core::named_enum! {\n" + "\n".join(lines) + "\n}\n"


def creation_list(text, cls):
    return re.findall(r"new\s+" + cls + r'\("([^"]+)"\)', text)


warheads = creation_list(source, "WarheadTypeClass")
weapons = creation_list(source, "WeaponTypeClass")
bullets = creation_list(bbdata, "BulletTypeClass")
crates = re.findall(r'"([^"]+)"', re.search(r"CrateNames\[CRATE_COUNT\]\s*=\s*\{(.*?)\};", const_cpp, re.S).group(1))
armors = re.findall(r'"([^"]+)"', re.search(r"ArmorName\[ARMOR_COUNT\]\s*=\s*\{(.*?)\};", const_cpp, re.S).group(1))
for label, items in [("warheads", warheads), ("weapons", weapons), ("bullets", bullets), ("crates", crates), ("armors", armors)]:
    if not items:
        sys.exit(f"no {label} found")

names_rs = "\n".join([
    "//! Names of Red Alert's rule-driven types, in the order the game creates them (so the",
    "//! numeric ids match the original enums).",
    "//!",
    "//! @generated by `rust/tools/gen_ra_rules.py` from `RULES.CPP`, `BBDATA.CPP` and",
    "//! `CONST.CPP`. Do not edit by hand.",
    "",
    named_enum("Warhead", "A warhead type (`WarheadType`, created in `Heap_Maximums`).", warheads),
    named_enum("Weapon", "A weapon type (`WeaponType`, created in `Heap_Maximums`).", weapons),
    named_enum("Projectile", "A projectile type (`BulletType`, created in `BBDATA.CPP`).", bullets),
    named_enum("Crate", "A crate power-up (`CrateType`, names from `CrateNames`).", crates),
    named_enum("Armor", "An armour class (`ArmorType`, names from `ArmorName`).", armors),
])

# ---------------------------------------------------------------------------------------
# Global rules.

body = re.search(r"class RulesClass\s*\{(.*?)\n\};", header, re.S).group(1)
field_types = {}
field_docs = {}
pending_doc = []
for line in body.splitlines():
    stripped = line.strip()
    if stripped.startswith("**") or stripped.startswith("/*") or stripped.startswith("//"):
        text = stripped.lstrip("/*").strip()
        if text:
            pending_doc.append(text)
        continue
    m = re.match(r"(fixed|int|unsigned|bool|LEPTON|MPHType|UnitType|CrateType)\s+(\w+)(:1)?\s*;", stripped)
    if m:
        ctype = "bool" if m.group(1) == "unsigned" and m.group(3) else m.group(1)
        field_types[m.group(2)] = ctype
        field_docs[m.group(2)] = " ".join(pending_doc)
    if stripped and not stripped.startswith("*"):
        pending_doc = []

ctor = re.search(r"RulesClass::RulesClass\(void\)\s*:(.*?)\n\{(.*?)\n\}", source, re.S)
defaults = dict(re.findall(r"(\w+)\(([^()]*(?:\([^()]*\)[^()]*)*)\)\s*,?\s*\n", ctor.group(1)))
for name, expr in re.findall(r"(\w+)\s*=\s*([^;=]+);", ctor.group(2)):
    if "=" not in expr:
        defaults[name] = expr.strip()
# EngineerDamage=(fixed)1 / (fixed)3 and chained `A = B = 0`.
for chain in re.findall(r"((?:\w+\s*=\s*)+)([^;=]+);", ctor.group(2)):
    for name in re.findall(r"(\w+)\s*=", chain[0]):
        defaults[name] = chain[1].strip()

CONSTS = {"CELL_LEPTON_W": "256"}
FIXED_CONSTS = {"fixed::_1_2": "Fixed::HALF", "fixed::_1_4": "Fixed::QUARTER", "fixed::_3_4": "Fixed::THREE_QUARTERS",
                "fixed::_1_3": "Fixed::THIRD", "fixed::_2_3": "Fixed::TWO_THIRDS"}


def int_expr(expr):
    e = expr.strip()
    for k, v in CONSTS.items():
        e = e.replace(k, v)
    e = re.sub(r"\(MPHType\)|\(LEPTON\)", "", e)
    if e == "MPH_IMMOBILE":
        return "0"
    if not re.fullmatch(r"[0-9xXa-fA-F\s*+()-]+", e):
        raise ValueError(expr)
    return str(eval(e))


def default_rust(field, expr):
    ctype = field_types[field]
    e = expr.strip()
    if e in field_types and e != field:  # e.g. EngineerCaptureLevel = ConditionRed
        return default_rust(e, defaults[e])
    if ctype == "fixed":
        if e in FIXED_CONSTS:
            return FIXED_CONSTS[e]
        if e.startswith('"'):
            return f"fixed({e})"
        m = re.fullmatch(r"\(fixed\)(\d+)\s*/\s*\(fixed\)(\d+)", e)
        if m:
            return f"Fixed::ratio({m.group(1)}, {m.group(2)})"
        return f"Fixed::from_int({int_expr(e)})"
    if ctype == "bool":
        return {"true": "true", "false": "false", "1": "true", "0": "false"}[e]
    if ctype in ("int", "LEPTON"):
        return int_expr(e)
    if ctype == "MPHType":
        return int_expr(e)
    if ctype == "UnitType":
        return "None" if e == "UNIT_NONE" else f"Some(UnitType::{camel(e[5:].lower())})"
    if ctype == "CrateType":
        name = e[len("CRATE_"):]
        idx = ["MONEY", "UNIT", "PARA_BOMB", "HEAL_BASE", "CLOAK", "EXPLOSION", "NAPALM", "SQUAD", "DARKNESS",
               "REVEAL", "SONAR", "ARMOR", "SPEED", "FIREPOWER", "ICBM", "TIMEQUAKE", "INVULN", "VORTEX"].index(name)
        return f"Crate::{camel(crates[idx])}"
    raise ValueError((field, expr))


RUST_TYPES = {"fixed": "Fixed", "int": "i32", "bool": "bool", "LEPTON": "i32", "MPHType": "u8",
              "UnitType": "Option<UnitType>", "CrateType": "Crate"}

sections = dict(re.findall(r'static char const \* const (\w+)\s*=\s*"([^"]+)";', source))
reads = []  # (field, getter, section, key, default_expr)
seen = set()
for reader in READERS:
    fn = re.search(r"bool RulesClass::" + reader + r"\(CCINIClass & ini\)\s*\{(.*?)\n\}", source, re.S).group(1)
    fn = re.sub(r"//[^\n]*", "", fn)
    for m in re.finditer(r"(\w+)\s*=\s*(MPHType\(_Scale_To_256\()?ini\.Get_(\w+)\((\w+),\s*\"([^\"]+)\",\s*([^;]*?)\)\)*\s*;", fn):
        field, scaled, getter, section, key, dflt = m.groups()
        if field not in field_types:
            print(f"skipping {field} (not a RulesClass field)", file=sys.stderr)
            continue
        if scaled:
            getter = "MPHRaw"
        reads.append((field, getter, sections[section], key, dflt.strip()))
        seen.add(field)

fields = [f for f in field_types if f in seen]
missing_defaults = [f for f in fields if f not in defaults]
if missing_defaults:
    sys.exit(f"no constructor default for {missing_defaults}")

GETTERS = {
    "Int": lambda f, k, d: f"s.get_int({k!r}).unwrap_or({d})",
    "Fixed": lambda f, k, d: f"s.get_fixed({k!r}).unwrap_or({d})",
    "Bool": lambda f, k, d: f"s.get_bool({k!r}).unwrap_or({d})",
    "Lepton": lambda f, k, d: f"s.get_fixed({k!r}).map_or({d}, |v| v.scale(256) as i32)",
    "MPHType": lambda f, k, d: f"s.get_int({k!r}).map_or({d}, scale_to_256)",
    "MPHRaw": lambda f, k, d: f"scale_to_256(s.get_int({k!r}).unwrap_or(i32::from({d})))",
    "UnitType": lambda f, k, d: f"s.get({k!r}).map_or({d}, |n| n.parse().ok())",
    "CrateType": lambda f, k, d: f"s.get({k!r}).and_then(|n| n.parse().ok()).unwrap_or({d})",
}

out = [
    "//! Red Alert's global rules (`RulesClass`), read from `RULES.INI`.",
    "//!",
    "//! @generated by `rust/tools/gen_ra_rules.py` from `RULES.H` and `RULES.CPP`. Do not",
    "//! edit by hand; change the generator instead.",
    "",
    "use cnc_core::Fixed;",
    "use cnc_core::ini::Ini;",
    "",
    "use super::names::Crate;",
    "use crate::UnitType;",
    "",
    "fn fixed(text: &str) -> Fixed {",
    "    text.parse().unwrap_or_default()",
    "}",
    "",
    "/// Scales a 0..=100 percentage to 0..=255 (`_Scale_To_256`).",
    "#[must_use]",
    "pub fn scale_to_256(value: i32) -> u8 {",
    "    (value.clamp(0, 100) * 256 / 100).min(255) as u8",
    "}",
    "",
    "/// Global game rules. Field defaults are the `RulesClass` constructor's.",
    "#[derive(Debug, Clone, PartialEq, Eq)]",
    "#[allow(clippy::struct_excessive_bools)]",
    "pub struct GlobalRules {",
]
field_section = {}
for field, getter, section, key, _ in reads:
    field_section.setdefault(field, (section, key, getter))
for f in fields:
    section, key, getter = field_section[f]
    doc = field_docs.get(f, "").replace("`", "'").strip()
    unit = {"LEPTON": " In leptons.", "MPHType": " Speed on the game's 0..=255 scale."}.get(field_types[f], "")
    if doc:
        out.append(f"    /// {doc}{unit}")
        out.append("    ///")
    elif unit:
        out.append(f"    ///{unit}")
        out.append("    ///")
    out.append(f"    /// `[{section}] {key}` (`{f}`).")
    out.append(f"    pub {snake(f)}: {RUST_TYPES[field_types[f]]},")
out += ["}", "", "impl Default for GlobalRules {", "    #[allow(clippy::too_many_lines)]", "    fn default() -> Self {", "        Self {"]
for f in fields:
    out.append(f"            {snake(f)}: {default_rust(f, defaults[f])},")
out += ["        }", "    }", "}", "", "impl GlobalRules {",
        "    /// Applies every straight-line setting from `ini`, in the original's order.",
        "    /// Missing sections and keys leave the current values alone.",
        "    #[allow(clippy::too_many_lines)]",
        "    pub fn read_ini(&mut self, ini: &Ini) {"]
current = None
for field, getter, section, key, dflt in reads:
    if section != current:
        if current is not None:
            out.append("        }")
        out.append(f"        if let Some(s) = ini.section(\"{section}\") {{")
        current = section
    target = f"self.{snake(field)}"
    if dflt == field or (dflt.startswith("(") and field in dflt):
        d = target
    elif dflt in field_types:
        d = f"self.{snake(dflt)}"
    else:
        d = default_rust(field, dflt)
    value = GETTERS[getter](field, key, d).replace("'", '"')
    if field_types[field] == "bool" and getter == "Fixed":
        value = f"s.get_fixed({key!r}).map_or({d}, |v| v != Fixed::ZERO)".replace("'", '"')
    elif field_types[field] == "int" and getter == "Fixed":
        value = f"s.get_fixed({key!r}).map_or({d}, |v| v.to_int() as i32)".replace("'", '"')
    elif field_types[field] == "fixed" and getter == "Int":
        value = f"s.get_int({key!r}).map_or({d}, |v| Fixed::from_int(v as u32))".replace("'", '"')
    out.append(f"            {target} = {value};")
out += ["        }", "    }", "}", ""]

OUT.mkdir(parents=True, exist_ok=True)
(OUT / "global.rs").write_text("\n".join(out))
(OUT / "names.rs").write_text(names_rs)
print(f"wrote {len(fields)} rules fields, {len(reads)} reads; {len(weapons)} weapons, {len(warheads)} warheads, "
      f"{len(bullets)} projectiles, {len(crates)} crates, {len(armors)} armors")
