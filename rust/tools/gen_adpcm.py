#!/usr/bin/env python3
"""Extracts the SOS ADPCM decoder tables from REDALERT/ITABLE.CPP and DTABLE.CPP.

Usage (from the repository root): python3 rust/tools/gen_adpcm.py
Rewrites rust/crates/cnc-assets/src/aud/sos_tables.rs (run `cargo fmt` after).
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]

def table(name, file):
    text = (ROOT / "REDALERT" / file).read_text(encoding="latin-1")
    body = re.search(name + r"\[\]\s*=\s*\{(.*?)\}\s*;", text, re.S).group(1)
    body = re.sub(r"//[^\n]*", "", body)
    return [int(v) for v in re.findall(r"-?\d+", body)]

index = table("IndexTable", "ITABLE.CPP")
diff = table("DiffTable", "DTABLE.CPP")
assert len(index) == len(diff) == 89 * 16, (len(index), len(diff))

def rows(values):
    return "\n".join(
        "    " + ", ".join(str(v) for v in values[i:i + 16]) + ","
        for i in range(0, len(values), 16)
    )

out = f"""//! Decoder tables for SOS ADPCM, as in `ITABLE.CPP` / `DTABLE.CPP`.
//!
//! Both are indexed by `step_index * 16 + token`. `INDEX` holds the next `step_index * 16`;
//! `DIFF` the signed difference to add to the predicted sample.
//!
//! @generated by `rust/tools/gen_adpcm.py`. Do not edit by hand.

/// Next step index, premultiplied by 16 (`IndexTable`).
pub(super) const INDEX: [u16; {len(index)}] = [
{rows(index)}
];

/// Sample difference (`DiffTable`).
pub(super) const DIFF: [i32; {len(diff)}] = [
{rows(diff)}
];
"""
dest = ROOT / "rust" / "crates" / "cnc-assets" / "src" / "aud" / "sos_tables.rs"
dest.parent.mkdir(parents=True, exist_ok=True)
dest.write_text(out)
print("wrote", dest.relative_to(ROOT))
