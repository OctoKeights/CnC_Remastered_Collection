#!/usr/bin/env python3
"""Extracts Blowfish's initial P-array and S-boxes from REDALERT/BLOWFISH.CPP.

Usage (from the repository root): python3 rust/tools/gen_blowfish.py
Rewrites rust/crates/cnc-core/src/crypto/blowfish_tables.rs (run `cargo fmt` after).
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
src = (ROOT / "REDALERT" / "BLOWFISH.CPP").read_text(encoding="latin-1")
p_block = re.search(r"P_Init\[[^\]]*\]\s*=\s*\{(.*?)\}\s*;", src, re.S).group(1)
s_block = re.search(r"S_Init\[4\]\[[^\]]*\]\s*=\s*\{(.*)\}\s*;", src, re.S).group(1)
hexes = lambda text: re.findall(r"0x([0-9A-Fa-f]{8})", text)
p = hexes(p_block)
s = hexes(s_block)
assert len(p) == 18 and len(s) == 1024, (len(p), len(s))

def rows(values):
    return "\n".join(
        "    " + ", ".join(f"0x{v.upper()[:4]}_{v.upper()[4:]}" for v in values[i:i + 6]) + ","
        for i in range(0, len(values), 6)
    )

out = [
    "//! Blowfish's initial tables (the hexadecimal digits of pi), as in `BLOWFISH.CPP`.",
    "//!",
    "//! @generated by `rust/tools/gen_blowfish.py`. Do not edit by hand.",
    "",
    "/// Initial P-array.",
    "pub(super) const P_INIT: [u32; 18] = [",
    rows(p),
    "];",
    "",
    "/// Initial S-boxes.",
    "pub(super) const S_INIT: [[u32; 256]; 4] = [",
]
for b in range(4):
    out += ["    [", rows(s[b * 256:(b + 1) * 256]), "    ],"]
out.append("];")
dest = ROOT / "rust" / "crates" / "cnc-core" / "src" / "crypto" / "blowfish_tables.rs"
dest.parent.mkdir(parents=True, exist_ok=True)
dest.write_text("\n".join(out) + "\n")
print("wrote", dest.relative_to(ROOT))
